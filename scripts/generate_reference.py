"""Write the generated reference pages, or check that they are current.

Writes under `docs/reference/`:

- `case-schema.md` from `cfd-craft describe` (`case_schema`);
- `result-schema.md` from `describe` (`result_schema`, `phase_profile_schema`);
- `python-api.md` from the docstrings of `python/cfd_craft/__init__.py` and
  `__main__.py`, read with `ast` (no build or import is needed);
- two blocks of `cli.md`, between `<!-- begin generated: NAME -->` and
  `<!-- end generated: NAME -->`: the usage text of `cfd-craft help` and the
  `exit_codes` of `describe`.

The output has no version, hash, compiler string, date or host path, so two runs
give identical bytes. `--check` writes nothing; it exits non-zero and names each
page that differs from the current build, and it also fails when a `CFD-` code
that occurs in the Rust or Python sources is missing from `docs/diagnostics.md`.
Failures are reported as `CFD-R002 reference.<field>` (docs/diagnostics.md).
"""

import argparse
import ast
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BINARY = "target/release/cfd-craft"
REFERENCE = "docs/reference"
GENERATED = "<!-- check: none: generated by scripts/generate_reference.py -->"
CODE_PATTERN = re.compile(r"CFD-[A-Z][0-9]{3}")
SKIPPED_DIRECTORIES = {
    ".git",
    ".venv",
    "venv",
    "target",
    "book",
    "node_modules",
    "__pycache__",
    "runs",
}
MARKERS = ("usage", "exit-codes")


def fail(field, message):
    sys.exit(f"CFD-R002 reference.{field}: {message}")


# --- native binary --------------------------------------------------------


def native_json(binary, command):
    """The JSON object a native command prints, or a coded failure."""
    try:
        done = subprocess.run(
            [str(binary), command],
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=60,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as error:
        fail("binary", f"cannot run `{binary} {command}`: {error}")
    if done.returncode != 0:
        fail("binary", f"`{binary} {command}` exited {done.returncode}")
    try:
        value = json.loads(done.stdout)
    except ValueError as error:
        fail("binary", f"`{binary} {command}` printed no JSON: {error}")
    if not isinstance(value, dict):
        fail("binary", f"`{binary} {command}` did not print a JSON object")
    return value


def need(mapping, key, field):
    if not isinstance(mapping, dict) or key not in mapping:
        fail(field, f"missing `{key}` in the native output")
    return mapping[key]


# --- schema pages ---------------------------------------------------------


def cell(text):
    """One table cell: single line, pipes escaped."""
    return re.sub(r"\s+", " ", str(text)).strip().replace("|", "\\|")


def anchor(name):
    return re.sub(r"[^a-z0-9_-]", "", name.lower().replace(" ", "-"))


def ref_link(ref, field):
    prefix = "#/definitions/"
    if not ref.startswith(prefix):
        fail(field, f"unsupported reference `{ref}`")
    name = ref[len(prefix) :]
    return f"[{name}](#{anchor(name)})"


def type_text(node, field):
    """The type of a schema node as Markdown."""
    if "$ref" in node:
        return ref_link(node["$ref"], field)
    if "allOf" in node:
        if len(node["allOf"]) != 1:
            fail(field, "`allOf` with more than one member is not supported")
        return type_text(node["allOf"][0], field)
    if "anyOf" in node:
        return " or ".join(type_text(n, field) for n in node["anyOf"])
    if "enum" in node:
        return " or ".join(f"`{v}`" for v in node["enum"])
    kind = node.get("type")
    if isinstance(kind, list):
        return " or ".join(f"`{k}`" for k in kind) + _bound(node)
    if kind == "array":
        items = type_text(need(node, "items", field), field)
        if node.get("minItems") is not None and node.get("minItems") == node.get(
            "maxItems"
        ):
            return f"array of {node['minItems']} {items}"
        return f"array of {items}"
    if kind == "object" and isinstance(node.get("additionalProperties"), dict):
        value = type_text(node["additionalProperties"], field)
        return f"object with string keys and values of {value}"
    if isinstance(kind, str):
        return f"`{kind}`" + _bound(node)
    fail(field, f"cannot describe the type {json.dumps(node, sort_keys=True)[:80]}")


def _bound(node):
    minimum = node.get("minimum")
    if minimum is None:
        return ""
    return f" (>= {minimum:g})"


def requirement(name, node, required):
    if name in required:
        return "required"
    if "default" in node:
        return "default `" + cell(json.dumps(node["default"], sort_keys=True)) + "`"
    return "optional"


def property_table(properties, required, field):
    lines = [
        "| Field | Type | Required | Description |",
        "|---|---|---|---|",
    ]
    for name in sorted(properties):
        node = properties[name]
        lines.append(
            f"| `{name}` | {cell(type_text(node, field + '.' + name))} | "
            f"{requirement(name, node, required)} | "
            f"{cell(node.get('description', ''))} |"
        )
    return lines


def object_section(heading, level, node, field):
    """Description, a note on unknown fields and the property table."""
    lines = [f"{'#' * level} {heading}", ""]
    if node.get("description"):
        lines += [re.sub(r"\s+", " ", node["description"]).strip(), ""]
    if node.get("additionalProperties") is False:
        lines += ["Unknown fields are rejected.", ""]
    properties = need(node, "properties", field)
    lines += property_table(properties, set(node.get("required", [])), field)
    return lines + [""]


def definition_sections(name, node, field):
    """Sections for one definition: object, enum, tagged union or string choice."""
    if "properties" in node:
        return object_section(name, 3, node, f"{field}.{name}")
    lines = [f"### {name}", ""]
    if node.get("description"):
        lines += [re.sub(r"\s+", " ", node["description"]).strip(), ""]
    if "enum" in node:
        lines += [
            "Allowed values: " + ", ".join(f"`{v}`" for v in node["enum"]) + ".",
            "",
        ]
        return lines
    variants = need(node, "oneOf", f"{field}.{name}")
    if all("properties" not in v for v in variants):
        lines += ["| Value | Description |", "|---|---|"]
        for variant in variants:
            values = need(variant, "enum", f"{field}.{name}")
            lines.append(
                f"| {', '.join(f'`{v}`' for v in values)} | {cell(variant.get('description', ''))} |"
            )
        return lines + [""]
    for variant in variants:
        kinds = variant.get("properties", {}).get("kind", {}).get("enum")
        if not kinds or len(kinds) != 1:
            fail(f"{field}.{name}", "a variant has no single `kind` value")
        lines += object_section(
            f"{name}, kind {kinds[0]}", 4, variant, f"{field}.{name}"
        )
    return lines


def schema_sections(root_heading, schema, field):
    """The root object at level 2, then its definitions at level 3."""
    lines = object_section(root_heading, 2, schema, field)
    definitions = schema.get("definitions", {})
    for name in sorted(definitions):
        lines += definition_sections(name, definitions[name], field)
    return lines


def case_schema_page(description):
    schema = need(description, "case_schema", "case-schema")
    lines = [
        "# Case schema",
        "",
        GENERATED,
        "",
        "This page lists every field of a case file. It is generated from the",
        "`case_schema` field of `cfd-craft describe`, whose descriptions are the doc",
        "comments of the Rust types. The schema dialect is JSON Schema draft-07.",
        "Units are in the field names; see [units and conventions](units-and-conventions.md).",
        "Tables are sorted by field name. The order in a case file does not matter.",
        "",
    ]
    lines += schema_sections("Case", schema, "case-schema")
    return "\n".join(lines).rstrip("\n") + "\n"


def result_schema_page(description):
    summary = need(description, "result_schema", "result-schema")
    profile = need(description, "phase_profile_schema", "result-schema")
    names = set(summary.get("definitions", {})) | set(profile.get("definitions", {}))
    if len(names) != len(summary.get("definitions", {})) + len(
        profile.get("definitions", {})
    ):
        fail("result-schema", "the two schemas define the same type name")
    lines = [
        "# Result schema",
        "",
        GENERATED,
        "",
        "This page lists the fields of `summary.json` and of the phase profile. It is",
        "generated from the `result_schema` and `phase_profile_schema` fields of",
        "`cfd-craft describe`. What the files mean and which checks `report` repeats",
        "is in the [result contract](../result-contract.md). A field without a default",
        "that is not required may be absent; null means unavailable, not zero.",
        "",
    ]
    lines += schema_sections("Summary", summary, "result-schema.summary")
    lines += [
        "The phase profile is the `timing` field of the `profile.json` that",
        "`cfd-craft profile` writes.",
        "",
    ]
    lines += schema_sections("Profile", profile, "result-schema.profile")
    return "\n".join(lines).rstrip("\n") + "\n"


# --- Python API page ------------------------------------------------------


def parse_python(path):
    try:
        text = (ROOT / path).read_text(encoding="utf-8")
        return ast.parse(text, filename=path)
    except (OSError, SyntaxError, ValueError) as error:
        fail("python-api", f"cannot read {path}: {error}")


def signature(function):
    args = function.args
    parts = []
    positional = args.posonlyargs + args.args
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    for arg, default in zip(positional, defaults, strict=True):
        parts.append(
            arg.arg if default is None else f"{arg.arg}={ast.unparse(default)}"
        )
    if args.vararg:
        parts.append("*" + args.vararg.arg)
    elif args.kwonlyargs:
        parts.append("*")
    for arg, default in zip(args.kwonlyargs, args.kw_defaults, strict=True):
        parts.append(
            arg.arg if default is None else f"{arg.arg}={ast.unparse(default)}"
        )
    if args.kwarg:
        parts.append("**" + args.kwarg.arg)
    return f"{function.name}({', '.join(parts)})"


def docstring(node, label):
    text = ast.get_docstring(node, clean=True)
    if not text:
        fail("python-api", f"{label} has no docstring")
    return text


def class_attributes(cls):
    """Names assigned as `self.NAME` in `__init__`, in source order."""
    names = []
    for item in cls.body:
        if isinstance(item, ast.FunctionDef) and item.name == "__init__":
            for node in ast.walk(item):
                if isinstance(node, ast.Assign):
                    for target in node.targets:
                        if (
                            isinstance(target, ast.Attribute)
                            and isinstance(target.value, ast.Name)
                            and target.value.id == "self"
                            and target.attr not in names
                        ):
                            names.append(target.attr)
    return names


def console_commands(tree):
    """Commands and arguments declared with argparse in `__main__.py`."""
    owners = {}
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Assign)
            and isinstance(node.value, ast.Call)
            and getattr(node.value.func, "attr", "") == "add_parser"
            and isinstance(node.targets[0], ast.Name)
        ):
            owners[node.targets[0].id] = node.value.args[0].value
    commands = {}
    top = []
    calls = sorted(
        (n for n in ast.walk(tree) if isinstance(n, ast.Call)),
        key=lambda n: (n.lineno, n.col_offset),
    )
    for call in calls:
        kind = getattr(call.func, "attr", "")
        if kind == "add_parser":
            commands.setdefault(call.args[0].value, [])
        elif kind == "add_argument":
            owner = call.func.value
            if (
                isinstance(owner, ast.Call)
                and getattr(owner.func, "attr", "") == "add_parser"
            ):
                target = commands.setdefault(owner.args[0].value, [])
            elif isinstance(owner, ast.Name) and owner.id in owners:
                target = commands.setdefault(owners[owner.id], [])
            else:
                target = top
            names = [a.value for a in call.args if isinstance(a, ast.Constant)]
            extra = {k.arg: ast.unparse(k.value) for k in call.keywords}
            label = ", ".join(f"`{n}`" for n in names)
            if "type" in extra:
                label += f" (`{extra['type']}`)"
            if extra.get("action", "").strip("'\"") == "version":
                label += " (prints the version)"
            target.append(label)
    return top, commands


def python_api_page():
    package = parse_python("python/cfd_craft/__init__.py")
    main = parse_python("python/cfd_craft/__main__.py")
    lines = [
        "# Python API",
        "",
        GENERATED,
        "",
        "This page is generated from the docstrings of `python/cfd_craft/__init__.py`",
        "and `python/cfd_craft/__main__.py`. Examples are in the guide chapter on",
        "the Python binding.",
        "",
        "## Module cfd_craft",
        "",
        docstring(package, "the package"),
        "",
        "`cfd_craft.__version__` is the installed distribution version.",
        "",
    ]
    for node in package.body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            lines += [
                f"### `{signature(node)}`",
                "",
                docstring(node, f"function {node.name}"),
                "",
            ]
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            bases = ", ".join(ast.unparse(b) for b in node.bases)
            lines += [
                f"### `{node.name}`",
                "",
                f"Subclass of `{bases}`." if bases else "",
                "",
                docstring(node, f"class {node.name}"),
                "",
            ]
            attributes = class_attributes(node)
            if attributes:
                lines += [
                    "Attributes: " + ", ".join(f"`{a}`" for a in attributes) + ".",
                    "",
                ]
    top, commands = console_commands(main)
    lines += [
        "## Console script",
        "",
        docstring(main, "`__main__.py`"),
        "",
        "Run it as `python -m cfd_craft COMMAND`.",
        "",
    ]
    if top:
        lines += ["Options before the command: " + "; ".join(top) + ".", ""]
    lines += ["| Command | Arguments |", "|---|---|"]
    for name in sorted(commands):
        lines.append(f"| `{name}` | {cell('; '.join(commands[name]) or 'none')} |")
    lines.append("")
    return "\n".join(line for line in lines if line is not None).rstrip("\n") + "\n"


# --- generated blocks of cli.md --------------------------------------------


def usage_block(binary):
    usage = need(native_json(binary, "help"), "usage", "cli.usage")
    if not isinstance(usage, str):
        fail("cli.usage", "`usage` is not a string")
    lines = []
    for index, part in enumerate(usage.split(" | ")):
        text = part if index == 0 else f"cfd-craft {part}"
        lines.append(f"- `{text}`")
    return lines


def exit_codes_block(description):
    codes = need(description, "exit_codes", "cli.exit-codes")
    lines = ["| Exit | Meaning |", "|---|---|"]
    for code in sorted(codes):
        lines.append(f"| {code} | {cell(codes[code])} |")
    return lines


def replace_block(text, name, lines):
    begin = f"<!-- begin generated: {name} -->"
    end = f"<!-- end generated: {name} -->"
    if (
        text.count(begin) != 1
        or text.count(end) != 1
        or text.index(begin) > text.index(end)
    ):
        fail("cli.markers", f"cli.md needs exactly one `{begin}` before one `{end}`")
    head, rest = text.split(begin)
    _, tail = rest.split(end)
    return head + begin + "\n" + "\n".join(lines) + "\n" + end + tail


def cli_page(description, binary):
    path = ROOT / REFERENCE / "cli.md"
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        fail("cli.markers", f"cannot read {REFERENCE}/cli.md: {error}")
    text = replace_block(text, "usage", usage_block(binary))
    return replace_block(text, "exit-codes", exit_codes_block(description))


# --- diagnostics catalog lint ----------------------------------------------


def source_codes():
    codes = set()
    for path in sorted(ROOT.rglob("*")):
        relative = path.relative_to(ROOT)
        if path.suffix not in {".rs", ".py"} or SKIPPED_DIRECTORIES & set(
            relative.parts
        ):
            continue
        if not path.is_file():
            continue
        try:
            codes |= set(CODE_PATTERN.findall(path.read_text(encoding="utf-8")))
        except (OSError, UnicodeDecodeError) as error:
            fail("diagnostics.sources", f"cannot read {relative}: {error}")
    return codes


def missing_codes():
    try:
        catalog = (ROOT / "docs/diagnostics.md").read_text(encoding="utf-8")
    except OSError as error:
        fail("diagnostics.catalog", f"cannot read docs/diagnostics.md: {error}")
    return sorted(source_codes() - set(CODE_PATTERN.findall(catalog)))


# --- driver ------------------------------------------------------------------


def generate(binary):
    """All generated files as `{path relative to the repository: text}`."""
    description = native_json(binary, "describe")
    return {
        f"{REFERENCE}/case-schema.md": case_schema_page(description),
        f"{REFERENCE}/result-schema.md": result_schema_page(description),
        f"{REFERENCE}/python-api.md": python_api_page(),
        f"{REFERENCE}/cli.md": cli_page(description, binary),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--binary", default=str(ROOT / DEFAULT_BINARY))
    parser.add_argument(
        "--check", action="store_true", help="write nothing; fail when a page differs"
    )
    args = parser.parse_args()
    pages = generate(Path(args.binary))
    if args.check:
        differing = []
        for relative, text in pages.items():
            try:
                current = (ROOT / relative).read_text(encoding="utf-8")
            except OSError:
                current = None
            if current != text:
                differing.append(relative)
        problems = [
            f"CFD-R002 reference.{Path(p).stem}: {p} differs from the generated page"
            for p in differing
        ]
        missing = missing_codes()
        if missing:
            problems.append(
                "CFD-R002 reference.diagnostics: not in docs/diagnostics.md: "
                + ", ".join(missing)
            )
        if problems:
            sys.exit("\n".join(problems))
        print(json.dumps({"pages": sorted(pages), "codes_missing": 0}))
        return
    for relative, text in pages.items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(json.dumps({"written": sorted(pages)}))


if __name__ == "__main__":
    main()
